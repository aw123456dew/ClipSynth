def _format_time(ms: int) -> str:
    total_sec = ms / 1000
    hours = int(total_sec // 3600)
    minutes = int((total_sec % 3600) // 60)
    seconds = int(total_sec % 60)
    millis = int(ms % 1000)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}.{millis:03d}"


def _parse_time_to_ms(t: str) -> float:
    """将 HH:MM:SS.mmm 格式转为毫秒数"""
    t = t.strip()
    if "." in t:
        main, frac = t.rsplit(".", 1)
    else:
        main, frac = t, "0"
    parts = main.split(":")
    h, m, s = int(parts[0]), int(parts[1]), int(parts[2])
    ms = int(frac.ljust(3, "0")[:3])
    return (h * 3600 + m * 60 + s) * 1000 + ms


def build_segmentation_prompt(
    utterances: list,
    speaker_aliases: dict,
    duration: str,
) -> str:
    sections = ["下面是视频的角色台词时间线，请根据上面的要求进行片段切分。\n\n"]

    for utt in utterances:
        text = utt.get("text", "")
        speaker = utt.get("speaker", "0")
        alias = speaker_aliases.get(speaker, f"说话人{speaker}")
        start_ms = utt.get("start_time", 0)
        end_ms = utt.get("end_time", 0)
        sections.append(
            f"[{_format_time(start_ms)} → {_format_time(end_ms)}] {alias}：{text}"
        )
        sections.append("")

    total_sec = (utterances[-1]["end_time"] - utterances[0]["start_time"]) / 1000 if utterances else 0
    sections.append(f"素材总时长：{total_sec:.0f}秒")
    sections.append(f"时长要求：{duration}")
    return "\n".join(sections)


