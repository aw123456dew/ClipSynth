def _format_time(ms: int) -> str:
    total_sec = ms / 1000
    hours = int(total_sec // 3600)
    minutes = int((total_sec % 3600) // 60)
    seconds = int(total_sec % 60)
    millis = int(ms % 1000)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}.{millis:03d}"


def build_segmentation_prompt(
    utterances: list,
    speaker_aliases: dict,
    duration: str,
) -> str:
    sections = ["下面是视频的角色台词时间线，请根据上面的要求进行片段切分。\n\n"]

    for i, utt in enumerate(utterances, 1):
        text = utt.get("text", "")
        speaker = utt.get("speaker", "0")
        alias = speaker_aliases.get(speaker, f"说话人{speaker}")
        start_ms = utt.get("start_time", 0)
        end_ms = utt.get("end_time", 0)
        sections.append(
            f"[{_format_time(start_ms)} → {_format_time(end_ms)}] {alias}：{text}"
        )
        sections.append("")

    total_sec = (utterances[-1]["end_time"] - utterances[0]["start_time"]) / 1000 if utterances else 0
    sections.append(f"素材总时长：{total_sec:.0f}秒")
    sections.append(f"时长要求：{duration}")
    return "\n".join(sections)


def build_script_generation_prompt(
    utterances: list,
    speaker_aliases: dict,
    segments: list,
    perspective: str,
    extra_requirements: str,
) -> str:
    lines = []

    lines.append("【完整台词】\n")
    for utt in utterances:
        text = utt.get("text", "")
        speaker = utt.get("speaker", "0")
        alias = speaker_aliases.get(speaker, f"说话人{speaker}")
        start_ms = utt.get("start_time", 0)
        end_ms = utt.get("end_time", 0)
        lines.append(f"[{_format_time(start_ms)} → {_format_time(end_ms)}] {alias}：{text}")
    lines.append("")

    lines.append("【需要解说配音的视频片段】\n")
    for i, seg in enumerate(segments, 1):
        start_s = seg.get("start_time", "")
        end_s = seg.get("end_time", "")
        lines.append(f"片段 {i}：{start_s} → {end_s}")
        lines.append(f"剧情：{seg.get('summary', '')}")
        lines.append("")

    lines.append("【额外配置】")
    lines.append(f"讲述角度：{perspective}")
    if extra_requirements.strip():
        lines.append(f"附加要求：{extra_requirements.strip()}")

    return "\n".join(lines)
